def mechanical_normalize(text):
    """
    Заменяет падежные формы слов из якорей на именительный падеж.
    Работает ДО AI-нормализатора — тупая замена по словарю.
    
    Вход:  текст после Whisper (например, "забрать посылку на почте")
    Выход: текст с исправленными падежами (например, "забрать посылку на почта")
    """
    if not text or not text.strip():
        return text
    
    # Загружаем якоря из профиля
    try:
        from profile import load_profile
        profile = load_profile()
        anchors = profile.get("anchors", {})
        people = profile.get("people_anchors", {})
    except ImportError:
        return text
    
    # Собираем все якорные слова
    all_anchors = {}
    for word in anchors.keys():
        all_anchors[word.lower()] = word.lower()
    for word in people.keys():
        all_anchors[word.lower()] = word.lower()
    
    if not all_anchors:
        return text
    
    # Словарь: падежная форма → именительный падеж
    replacements = {}
    
    for base in all_anchors.keys():
        # Стандартные падежные окончания для русского языка
        # Заменяем окончание на пустое, получая основу
        if base.endswith("а"):
            stem = base[:-1]  # основа: почт, мам, работ
        elif base.endswith("ин"):
            stem = base  # магазин — основа совпадает
        elif base.endswith("я"):
            stem = base[:-1]
        else:
            stem = base  # дом, пап — основа
        
        # Генерируем падежные формы и связываем с именительным
        # Для слов на -а (почта, работа, мама)
        if base.endswith("а"):
            forms = {
                base: base,           # почта
                stem + "е": base,     # почте
                stem + "у": base,     # почту
                stem + "ы": base,     # почты
                stem + "ой": base,    # почтой
                stem + "ою": base,    # почтою
            }
        # Для слов на согласный (магазин, дом)
        elif base.endswith("н") or base.endswith("м"):
            forms = {
                base: base,           # магазин
                base + "а": base,    # магазина
                base + "у": base,    # магазину
                base + "ом": base,   # магазином
                base + "е": base,    # магазине
            }
        # Для остальных (папа, дядя)
        else:
            forms = {
                base: base,           # папа
                stem + "ы": base,    # папы
                stem + "е": base,    # папе
                stem + "у": base,    # папу
                stem + "ой": base,   # папой
            }
        
        # Добавляем формы в словарь замен, исключая сам именительный
        for form, replacement in forms.items():
            if form != base:
                replacements[form] = replacement
    
    # Добавляем ручные замены для особых случаев
    manual = {
        "домой": "дома",
        "дом": "дома",
        "дому": "дома",
        "из дома": "дома",
        "к дому": "дома",
    }
    replacements.update(manual)
    
    # Заменяем слова в тексте
    words = text.split()
    new_words = []
    for word in words:
        clean = word.strip(",.!?;:«»\"'()[]").lower()
        if clean in replacements:
            new_words.append(replacements[clean])
        else:
            new_words.append(word)
    
    result = " ".join(new_words)
    
    if result != text:
        print(f"   🔧 Механическая правка: «{text[:60]}...» → «{result[:60]}...»" if len(text) > 60 else f"   🔧 Механическая правка: «{text}» → «{result}»")
    
    return result


def ai_normalize(text):
    """
    Принимает сырой текст от Whisper, возвращает нормализованную строку.
    
    Вход:  сырой текст (например, "Напомню купить Расторопше в 1730 домой")
    Выход: нормализованная строка (например, "напомни купить расторопшу сегодня в 17:30 дома")
    
    Использует якоря мест и людей из профиля + триггерные слова.
    """
    if not text or not text.strip():
        return text
    
    # Загружаем якоря из профиля
    try:
        from profile import load_profile
        profile = load_profile()
        anchors = profile.get("anchors", {})
        people = profile.get("people_anchors", {})
    except ImportError:
        anchors = {}
        people = {}
    
    # Собираем списки для промпта
    place_list = ", ".join(list(anchors.keys())[:10]) if anchors else "(нет)"
    people_list = ", ".join(list(people.keys())[:10]) if people else "(нет)"
    
    # Триггерные слова
    triggers = ["напомни", "ПРИКАЗЫВАЮ", "напомню", "напомня", "на помни",
                "приказыва ю", "приказы ваю", "приказую"]
    trigger_list = ", ".join(triggers)
    
    # Формируем полный промпт с якорями и триггерами
    full_prompt = PROMPT_NORMALIZE.replace(
        "Места: []", f"Места: [{place_list}]"
    ).replace(
        "Люди: []", f"Люди: [{people_list}]"
    )
    
    # Добавляем триггеры в промпт
    full_prompt += f"\n\nТРИГГЕРНЫЕ СЛОВА (не трогай их): {trigger_list}"
    text = mechanical_normalize(text)
    
    # Пробуем Bothub
    result = _call_bothub(full_prompt, text)
    
    # Если Bothub недоступен — Timeweb
    if not result:
        print("   🔄 Bothub недоступен, пробую Timeweb...")
        result = _call_timeweb(full_prompt, text)
    
    if result:
        result = result.strip().strip('"').strip("'")
        # Защита: если AI вернул слишком короткий или слишком длинный текст
        if len(result) < len(text) * 0.3 or len(result) > len(text) * 2.5:
            print(f"   ⚠️ AI исказил текст. Использую исходный.")
            return text
        if result:
            return result
    
    print(f"   ⚠️ AI-нормализатор не ответил. Использую исходный текст.")
    return text
    
    
    
    
